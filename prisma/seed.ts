async function seed() {
  console.log("Seeding database...");
  
  // Seed scoring weights
  const weightData = [
    { category: "requiredDocuments", weight: 0.40, description: "Required Documents Score" },
    { category: "proofOfFunds", weight: 0.20, description: "Proof of Funds Score" },
    { category: "purposeMatch", weight: 0.15, description: "Purpose Match Score" },
    { category: "qualificationsLanguage", weight: 0.10, description: "Qualifications & Language Score" },
    { category: "healthInsurance", weight: 0.05, description: "Health & Insurance Score" },
    { category: "priorTravelHistory", weight: 0.05, description: "Prior Travel History Score" },
    { category: "ageOther", weight: 0.05, description: "Age & Other Factors Score" },
  ];
  
  for (const w of weightData) {
    await db.scoringWeight.upsert({
      where: { category: w.category },
      update: w,
      create: w,
    });
  }
  console.log(`Seeded ${weightData.length} scoring weights`);

  // Seed countries
  for (const country of countries) {
    const totalMonthly = country.cost.monthlyRentUSD + country.cost.monthlyFoodUSD + country.cost.monthlyTransportUSD + country.cost.healthInsuranceUSD;

    // Create or update country (upsert)
    const createdCountry = await db.country.upsert({
      where: { code: country.code },
      update: {
        name: country.name,
        flagEmoji: country.flagEmoji,
        continent: country.continent,
        currency: country.currency,
        currencyCode: country.currencyCode,
        timezone: country.timezone,
        visaFree: country.visaFree,
        visaOnArrival: country.visaOnArrival,
        etaAvailable: country.etaAvailable,
        safetyRating: country.safetyRating,
        safetySummary: country.safetySummary,
        bestTravelMonths: country.bestTravelMonths,
        avgTempC: country.avgTempC,
        monthlyTemps: country.monthlyTemps,
        processingDaysMin: country.processingDaysMin,
        processingDaysMax: country.processingDaysMax,
        sourceUrl: country.sourceUrl,
        parserVersion: "1.0.0",
        parserConfidence: 0.88,
      },
      create: {
        code: country.code,
        name: country.name,
        flagEmoji: country.flagEmoji,
        continent: country.continent,
        currency: country.currency,
        currencyCode: country.currencyCode,
        timezone: country.timezone,
        visaFree: country.visaFree,
        visaOnArrival: country.visaOnArrival,
        etaAvailable: country.etaAvailable,
        safetyRating: country.safetyRating,
        safetySummary: country.safetySummary,
        bestTravelMonths: country.bestTravelMonths,
        avgTempC: country.avgTempC,
        monthlyTemps: country.monthlyTemps,
        processingDaysMin: country.processingDaysMin,
        processingDaysMax: country.processingDaysMax,
        sourceUrl: country.sourceUrl,
        parserVersion: "1.0.0",
        parserConfidence: 0.88,
      },
    });

    // Create visa types
    for (const vt of country.visaTypes) {
      await db.visaType.create({
        data: {
          countryId: createdCountry.id,
          type: vt.type,
          description: vt.description,
          maxDuration: vt.maxDuration,
          extensions: vt.extensions,
          multipleEntry: vt.multipleEntry,
          sourceUrl: country.sourceUrl,
          parserConfidence: 0.88,
        },
      });
    }

    // Create requirements
    for (const req of country.requirements) {
      await db.visaRequirement.create({
        data: {
          countryId: createdCountry.id,
          category: req.category,
          requirement: req.requirement,
          mandatory: req.mandatory,
          description: req.description,
          scoringWeight: req.scoringWeight,
          sourceUrl: country.sourceUrl,
          parserConfidence: 0.88,
        },
      });
    }

    // Create cost profile
    await db.costProfile.create({
      data: {
        countryId: createdCountry.id,
        visaFeeUSD: country.cost.visaFeeUSD,
        serviceFeeUSD: country.cost.serviceFeeUSD,
        processingDays: country.processingDaysMax > 0 ? Math.round((country.processingDaysMin + country.processingDaysMax) / 2) : 0,
        monthlyLivingUSD: totalMonthly,
        monthlyRentUSD: country.cost.monthlyRentUSD,
        monthlyFoodUSD: country.cost.monthlyFoodUSD,
        monthlyTransportUSD: country.cost.monthlyTransportUSD,
        healthInsuranceUSD: country.cost.healthInsuranceUSD,
        totalMonthlyUSD: totalMonthly,
        currency: country.currencyCode,
        parserConfidence: 0.85,
      },
    });
  }

  console.log(`Seeded ${countries.length} countries with visa types, requirements, and cost profiles`);
  console.log("Seed complete!");
}

seed()
  .catch((e) => {
    console.error("Seed error:", e);
    process.exit(1);
  })
  .finally(() => {
    db.$disconnect();
  });
